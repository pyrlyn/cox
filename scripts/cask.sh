# Print a Homebrew cask for one cox release: the CLI's, or with --app the macOS
# app's (T37.32.2, DT§7).
#
#   scripts/cask.sh <version> <sha256-aarch64>        > Casks/cox.rb
#   scripts/cask.sh --app <version> <sha256-dmg>      > Casks/cox-app.rb
#
# macOS is Apple Silicon only, so each cask has one (arm64) download.
#
# The release workflow writes the output to pyrlyn/homebrew-tap on every
# release, so the files there are generated, never edited by hand: change this
# script instead.
#
# The app cask installs the notarized Cox-<version>-arm64.dmg the release
# publishes and links the CLI bundled in it, so `brew install --cask cox-app`
# gives the app and a `cox` that never drift apart. Sparkle updates the app in
# place, hence auto_updates. Its zap leaves ~/.cox alone: the CLI shares it.

set -euo pipefail

APP=false
if [ "${1:-}" = --app ]; then
  APP=true
  shift
fi

if [ $# -ne 2 ]; then
  echo "usage: $0 [--app] <version> <sha256>" >&2
  exit 2
fi

VERSION="${1#v}"
SHA_ARM="$2"

if ! printf '%s' "$SHA_ARM" | grep -Eq '^[0-9a-f]{64}$'; then
  echo "not a sha256: $SHA_ARM" >&2
  exit 2
fi

if [ "$APP" = true ]; then
  cat <<EOF
# Generated by scripts/cask.sh in pyrlyn/cox on every release. Do not edit:
# the next release overwrites this file. Change scripts/cask.sh instead.
cask "cox-app" do
  version "${VERSION}"
  sha256 "${SHA_ARM}"

  url "https://github.com/pyrlyn/cox/releases/download/v#{version}/Cox-#{version}-arm64.dmg"
  name "Cox"
  desc "Desktop client for the cox coding agent"
  homepage "https://github.com/pyrlyn/cox"

  livecheck do
    url :homepage
    strategy :github_latest
  end

  auto_updates true
  depends_on arch: :arm64
  depends_on macos: ">= :tahoe"

  app "Cox.app"
  binary "#{appdir}/Cox.app/Contents/Helpers/cox"

  zap trash: [
    "~/Library/Caches/io.github.pyrlyn.cox",
    "~/Library/HTTPStorages/io.github.pyrlyn.cox",
    "~/Library/Preferences/io.github.pyrlyn.cox.plist",
    "~/Library/Saved Application State/io.github.pyrlyn.cox.savedState",
  ]
end
EOF
  exit 0
fi

cat <<EOF
# Generated by scripts/cask.sh in pyrlyn/cox on every release. Do not edit:
# the next release overwrites this file. Change scripts/cask.sh instead.
cask "cox" do
  version "${VERSION}"
  sha256 "${SHA_ARM}"

  url "https://github.com/pyrlyn/cox/releases/download/v#{version}/cox-aarch64-apple-darwin.tar.xz"
  name "cox"
  desc "Modular terminal coding agent"
  homepage "https://github.com/pyrlyn/cox"

  livecheck do
    url :homepage
    strategy :github_latest
  end

  depends_on arch: :arm64

  # cox installs into ~/.local/bin via install.sh; Homebrew only delivers the
  # tarball. Nothing is linked into the prefix.
  stage_only true

  postflight do
    set_ownership "\#{staged_path}/cox"
  end

  uninstall delete: "\#{staged_path}/cox"

  zap trash: "~/.cox"
end
EOF