#
# Print the Homebrew cask for one cox release.
#
#   scripts/cask.sh <version> <sha256-aarch64>
#   scripts/cask.sh --app <version> <build> <sha256-dmg>
#
# macOS is Apple Silicon only, so the cask has one (arm64) archive.
#
# --app prints Casks/cox-app.rb, the macOS app (T37.32.2, DT§7) from the notarized
# Cox-<version>-<build>-arm64.dmg of the same release. Sparkle updates the app, so
# the cask says auto_updates and livechecks the appcast. It installs no binary:
# the app's Install Command-Line Tool and the cox cask each give one `cox`, and
# two on PATH would drift apart.
#
# The release workflow writes the output to Casks/cox.rb in pyrlyn/homebrew-tap
# on every release (Casks/cox-app.rb once T37.32.4 wires it in), so the files
# there are generated, never edited by hand: change this script instead.

set -euo pipefail

APP=false
if [ "${1:-}" = --app ]; then
  APP=true
  shift
fi

if { $APP && [ $# -ne 3 ]; } || { ! $APP && [ $# -ne 2 ]; }; then
  echo "usage: $0 <version> <sha256-aarch64> | --app <version> <build> <sha256-dmg>" >&2
  exit 2
fi

VERSION="${1#v}"
if $APP; then
  BUILD="$2"
  SHA_ARM="$3"
else
  SHA_ARM="$2"
fi

if ! printf '%s' "$SHA_ARM" | grep -Eq '^[0-9a-f]{64}$'; then
  echo "not a sha256: $SHA_ARM" >&2
  exit 2
fi

if $APP; then
  if ! printf '%s' "$BUILD" | grep -Eq '^[0-9]+$'; then
    echo "not a build number: $BUILD" >&2
    exit 2
  fi
  cat <<EOF
# Generated by scripts/cask.sh in pyrlyn/cox on every release. Do not edit:
# the next release overwrites this file. Change scripts/cask.sh instead.
cask "cox-app" do
  version "${VERSION},${BUILD}"
  sha256 "${SHA_ARM}"

  url "https://github.com/pyrlyn/cox/releases/download/v#{version.csv.first}/Cox-#{version.csv.first}-#{version.csv.second}-arm64.dmg"
  name "Cox"
  desc "Native macOS app for the cox coding agent"
  homepage "https://github.com/pyrlyn/cox"

  livecheck do
    url "https://github.com/pyrlyn/cox/releases/latest/download/appcast.xml"
    strategy :sparkle
  end

  auto_updates true
  depends_on arch: :arm64
  depends_on macos: ">= :tahoe"

  app "Cox.app"

  # ~/.cox is shared with the cox CLI, so zap leaves it.
  zap trash: [
    "~/Library/Caches/io.github.pyrlyn.cox",
    "~/Library/HTTPStorages/io.github.pyrlyn.cox",
    "~/Library/Preferences/io.github.pyrlyn.cox.plist",
    "~/Library/Saved Application State/io.github.pyrlyn.cox.savedState",
  ]
end
EOF
  exit 0
fi

cat <<EOF
# Generated by scripts/cask.sh in pyrlyn/cox on every release. Do not edit:
# the next release overwrites this file. Change scripts/cask.sh instead.
cask "cox" do
  version "${VERSION}"
  sha256 "${SHA_ARM}"

  url "https://github.com/pyrlyn/cox/releases/download/v#{version}/cox-aarch64-apple-darwin.tar.xz"
  name "cox"
  desc "Modular terminal coding agent"
  homepage "https://github.com/pyrlyn/cox"

  livecheck do
    url :homepage
    strategy :github_latest
  end

  depends_on arch: :arm64

  # cox installs into ~/.local/bin via install.sh; Homebrew only delivers the
  # tarball. Nothing is linked into the prefix.
  stage_only true

  postflight do
    set_ownership "\#{staged_path}/cox"
  end

  uninstall delete: "\#{staged_path}/cox"

  zap trash: "~/.cox"
end
EOF